#!/usr/bin/env bun
/**
 * Fold.ts — the Tex nightly fold (Tex ISA F22, ISC-309 to ISC-316).
 *
 * Once a night it reads the principal's running thread (LIFEOS/RELAY/bridge/thread.ts, F18) from the message after
 * its last run, asks one model call per batch what in those texts is worth remembering, and writes the answers as
 * proposals into the memory reviewer's existing queue (MEMORY/OBSERVABILITY/pending-proposals.jsonl, the rows Pulse
 * and ProposalDecide.ts already decide). It also rewrites the derived workstreams file the one-pager reads.
 *
 * It recommends and never acts (OPERATIONAL_PREFERENCES § Autonomy & approval):
 *   - it reads the thread's main/ log and zoom files without the bridge's writer lock, and writes nothing there;
 *   - its only writes are new `pending` queue rows (appended, never a rewrite of existing rows), workstreams.md, its
 *     cursor, and the context dir's .gitignore. People, Cortex and memory files are read at most, never written;
 *   - every row's target kind and file are set by code (identity → PRINCIPAL_IDENTITY.md, contacts → CONTACTS.md),
 *     its status is `pending`, and its confidence stays under the reviewer's auto-apply bar. Any other field the model
 *     returns (a path, a status, an "apply") is dropped unread.
 *
 * Thread text is data. It goes to the model inside one <thread> block whose frame tags are defanged, tool output is
 * marked [untrusted] with its kind tags quoted (thread.ts defangKindTags), and the system prompt says to never obey
 * it. The model has no tools (Inference.ts, claude CLI lane); the code check below is the barrier, not the prompt.
 *
 * Every proposal cites at least one thread message by id, each one a message read in this batch whose zoom file
 * (zoom/<id>+1.txt) exists, plus its transport tid when it has one. A correction names a stored fact by id; its old
 * text and date are copied by code from the store, never written by the model.
 *
 * Login codes, passwords and secret-shaped values are scrubbed before the model sees a message (thread.ts
 * redactSecrets, then Boundary.redact, then a code and password pass), and every token those passes removed is
 * scrubbed again from anything the model returns.
 *
 * Usage:
 *   bun LIFEOS/RELAY/context/Fold.ts run [--json] [--thread <dir>] [--dry-run]
 *   bun LIFEOS/RELAY/context/Fold.ts status
 */
