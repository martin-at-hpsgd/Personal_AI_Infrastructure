/**
 * Vera Profile — deterministic Profile.md generation from a person's ledger.
 *
 * The profile is the artifact: this file renders it; it stores nothing.
 * personal-sensitivity rows are excluded from EVERY rendered surface.
 * The header line carries the 1-100 VERA composite and one score per branch,
 * computed at read time from the leaves; the body shows each branch as a
 * shape (per-leaf outline) and its leaf bars.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type AxesTree, type ClaimRow, type LeafScore } from "./Schema";
import { DEFAULT_CONFIG, type ScoringConfig, branchComposites, composite, scoreTree, scoreable } from "./Scoring";
import { analysisCoversPrivacy, analysisPath, ledgerFingerprint, personDir } from "./Store";
import { renderOutputSection } from "./Output";

const BAR_WIDTH = 20;

function bar(score: LeafScore): string {
  if (score.insufficient || score.estimate === null) {
    return "░".repeat(BAR_WIDTH) + "  (insufficient signal)";
  }
  const filled = Math.round(score.estimate * BAR_WIDTH);
  const traj = score.trajectory === null ? "" : score.trajectory > 0.005 ? " ↗" : score.trajectory < -0.005 ? " ↘" : " →";
  return (
    "█".repeat(filled) + "·".repeat(BAR_WIDTH - filled) +
    `  ${score.estimate.toFixed(2)} ±${score.interval.toFixed(2)} (n≈${score.n})${traj}`
  );
}

/** Per-branch shape: a compact outline of the branch's leaf estimates. */
function branchShape(leaves: LeafScore[]): string {
  const glyphs = leaves.map((l) => {
    if (l.insufficient || l.estimate === null) return "·";
    if (l.estimate >= 0.75) return "▲";
    if (l.estimate >= 0.5) return "◆";
    return "▽";
  });
  return glyphs.join(" ");
}

export function renderProfile(
  _slug: string,
  title: string,
  rows: ClaimRow[],
  axes: AxesTree,
  cfg: ScoringConfig = DEFAULT_CONFIG,
  now = Date.now(),
): string {
  const pub = scoreable(rows); // personal rows never render
  const scores = scoreTree(rows, axes, cfg, now);
  const byBranch = new Map<string, LeafScore[]>();
  for (const s of scores) {
    if (!byBranch.has(s.branch)) byBranch.set(s.branch, []);
    byBranch.get(s.branch)!.push(s);
  }

  const lines: string[] = [];
  const generatedFrom = pub.length;
  const comp = composite(scores);
  lines.push(`# Vera — ${title}`);
  lines.push("");
  lines.push(`**VERA ${comp.score}** / 100 · evidence n≈${comp.n} · coverage ${Math.round(comp.coverage * 100)}% · branches: ${branchComposites(scores).map((b) => `${b.branch} ${b.composite.score}`).join(" · ")}`);
  lines.push("");
  lines.push(`> Generated by Vera from ${generatedFrom} claim rows. Do not edit — edit the ledger.`);
  lines.push(`> This profile is a current best reconstruction, not a verdict. Every score`);
  lines.push(`> carries its evidence and its confidence; absence of evidence widens the`);
  lines.push(`> interval and never subtracts. The VERA composite runs 1-100, where 100`);
  lines.push(`> is a perfectly kind, perfectly intelligent ASI — humans top out well below.`);
  lines.push("");
  const analysisFile = analysisPath(_slug);
  if (existsSync(analysisFile)) {
    try {
      const a = JSON.parse(readFileSync(analysisFile, "utf8")) as { analysis: string; bullets: string[]; fingerprint?: string; personal_stamp?: string };
      lines.push(`## Analysis`);
      lines.push("");
      if (!analysisCoversPrivacy(a, rows)) {
        // Written while a row now marked personal could still have been public: withhold the text entirely.
        lines.push(`> Withheld: the ledger's personal-sensitivity rows changed since this analysis was written. Run \`bun LIFEOS/VERA/Assess.ts --person ${_slug}\` to refresh it.`);
        lines.push("");
      } else {
        if (a.fingerprint !== ledgerFingerprint(rows)) {
          const then = Number((a.fingerprint ?? "").split(":")[0]) || "?";
          lines.push(`> Written for an earlier ledger (${then} rows; now ${rows.length}). Run \`bun LIFEOS/VERA/Assess.ts --person ${_slug}\` to refresh it.`);
          lines.push("");
        }
        lines.push(a.analysis);
        lines.push("");
        for (const b of a.bullets) lines.push(`- ${b}`);
        lines.push("");
      }
    } catch { /* analysis optional */ }
  }
  const output = renderOutputSection(_slug);
  if (output) lines.push(output);
  lines.push(`## Shape`);
  lines.push("");
  lines.push("```");
  for (const [branch, leaves] of byBranch) {
    lines.push(`${branch.padEnd(12)} ${branchShape(leaves)}`);
  }
  lines.push("```");
  lines.push("");
  for (const [branch, leaves] of byBranch) {
    lines.push(`## ${branch[0]!.toUpperCase()}${branch.slice(1)}`);
    lines.push("");
    lines.push("```");
    for (const l of leaves) {
      lines.push(`${l.leaf.padEnd(20)} ${bar(l)}`);
    }
    lines.push("```");
    lines.push("");
  }

  lines.push(`## Claims`);
  lines.push("");
  const byAxis = new Map<string, ClaimRow[]>();
  for (const r of pub) {
    const key = r.axes[0] ?? "untagged";
    if (!byAxis.has(key)) byAxis.set(key, []);
    byAxis.get(key)!.push(r);
  }
  for (const [axis, list] of [...byAxis.entries()].sort()) {
    lines.push(`### ${axis}`);
    lines.push("");
    for (const r of list.sort((a, b) => b.happened.localeCompare(a.happened))) {
      const res =
        r.kind === "verifiable"
          ? r.resolution === "resolved_true" ? " ✓" : r.resolution === "resolved_false" ? " ✗" : " ⏳"
          : "";
      lines.push(`- ${r.happened} · [${r.kind}]${res} ${r.statement} — ${r.source} (conf ${r.confidence})`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

export function writeProfile(slug: string, title: string, rows: ClaimRow[], axes: AxesTree, cfg: ScoringConfig = DEFAULT_CONFIG, now = Date.now()): string {
  const p = join(personDir(slug), "Profile.md");
  writeFileSync(p, renderProfile(slug, title, rows, axes, cfg, now) + "\n");
  return p;
}
