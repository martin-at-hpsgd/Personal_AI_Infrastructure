/**
 * The carrier as settings.json states it — a tier alias ("fable", "opus[1m]") or a pinned
 * id — resolved to the Claude id it runs today. An alias resolves through CURRENT, so the
 * answer moves when ModelSync bumps a tier; that movement is exactly what the BLE
 * carrier-change trigger watches. Null when the string is neither.
 */
export function resolveCarrierId(setting: string | null | undefined): string | null {
  if (!setting) return null;
  const s = setting.trim().replace(/\[1m\]$/i, "");
  if ((TIER_NAMES as readonly string[]).includes(s)) return CURRENT[s as ClaudeTier];
  return parseClaudeId(s) ? s : null;
}

