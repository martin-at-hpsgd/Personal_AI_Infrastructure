import { readFileSync } from "node:fs";
import { join } from "node:path";

export type ClaudeTier = "opus" | "sonnet" | "haiku" | "fable";

const TIER_NAMES = ["opus", "sonnet", "haiku", "fable"] as const;

export type ParsedClaudeId = { family: string; tier: ClaudeTier | null; version: [number, number]; date?: string };

/**
 * `claude-<family>-<major>[-<minor>][-<yyyymmdd>]`, with any trailing `[1m]`
 * context suffix stripped. Minor is 1–3 digits so an 8-digit date can never be
 * read as a minor version (`claude-opus-4-20250514` → 4.0, dated).
 */
export function parseClaudeId(raw: string): ParsedClaudeId | null {
  const id = raw.trim().replace(/\[[^\]]*\]$/, "");
  const m = id.match(/^claude-([a-z]+)-(\d+)(?:-(\d{1,3}))?(?:-(\d{8}))?$/);
  if (!m) return null;
  const family = m[1];
  const tier = (TIER_NAMES as readonly string[]).includes(family) ? (family as ClaudeTier) : null;
  return { family, tier, version: [Number(m[2]), Number(m[3] ?? 0)], date: m[4] };
}

/** >0 when `a` is a newer version than `b`; throws on an unparsable id (fail loud). */
export function cmpClaudeVersion(a: string, b: string): number {
  const pa = parseClaudeId(a);
  const pb = parseClaudeId(b);
  if (!pa || !pb) throw new Error(`cmpClaudeVersion: unparsable id (${a} vs ${b})`);
  return pa.version[0] - pb.version[0] || pa.version[1] - pb.version[1];
}

/** Canonical undated id for a family+version ("Claude Haiku 4.5" → claude-haiku-4-5). */
export function canonicalId(family: string, version: [number, number]): string {
  return version[1] === 0 ? `claude-${family}-${version[0]}` : `claude-${family}-${version[0]}-${version[1]}`;
}

/** $/MTok. Generated by ModelSync from the public pricing page — never hand-edited. */
export type Pricing = { input: number; cacheWrite5m: number; cacheWrite1h: number; cacheRead: number; output: number };
export const PRICING_PATH = join(import.meta.dir, "model-pricing.json");
let pricingTable: Record<string, Pricing> | null = null;
function loadPricing(): Record<string, Pricing> {
  if (pricingTable) return pricingTable;
  try { pricingTable = (JSON.parse(readFileSync(PRICING_PATH, "utf8")) as { models: Record<string, Pricing> }).models ?? {}; }
  catch { pricingTable = {}; }
  return pricingTable;
}

export type PriceMatch = { pricing: Pricing; key: string; matchedBy: "exact" | "version" | "tier" };

/**
 * Price for any served model id: exact row → same family+version (dated ids,
 * `[1m]` suffix) → the tier's CURRENT row (an id newer than the last sync prices
 * at its tier's rate until the next sync) → null.
 */
export function pricingFor(model: string): PriceMatch | null {
  const table = loadPricing();
  const bare = model.trim().replace(/\[[^\]]*\]$/, "");
  if (table[bare]) return { pricing: table[bare], key: bare, matchedBy: "exact" };
  const p = parseClaudeId(bare);
  if (!p) return null;
  const canon = canonicalId(p.family, p.version);
  if (table[canon]) return { pricing: table[canon], key: canon, matchedBy: "version" };
  if (p.tier) {
    const cur = parseClaudeId(CURRENT[p.tier]);
    const curKey = cur ? canonicalId(cur.family, cur.version) : CURRENT[p.tier];
    if (table[curKey]) return { pricing: table[curKey], key: curKey, matchedBy: "tier" };
  }
  return null;
}

