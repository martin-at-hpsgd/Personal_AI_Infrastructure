/** The Inference.ts options the fold sets (a subset of InferenceOptions). */
export interface FoldInferenceCall {
  systemPrompt: string; userPrompt: string; level: "medium"; vendor: "anthropic";
  allowVendorFallback: false; persistSession: false; expectJson: true; timeout: number;
}
export type FoldInferenceFn = (options: FoldInferenceCall) => Promise<{ success: boolean; output: string; error?: string }>;

/**
 * The fold's model: Inference.ts at level medium on the Claude subscription lane (the claude CLI, which strips the
 * API-key env and runs with no tools), no vendor fallback, and no session transcript.
 */
export function foldModelFromInference(inference?: FoldInferenceFn, timeoutMs = 180_000): FoldModel {
  return async (request) => {
    const call = inference ?? ((await import("../../TOOLS/Inference.ts")).inference as unknown as FoldInferenceFn);
    const r = await call({
      systemPrompt: request.system, userPrompt: request.user, level: "medium", vendor: "anthropic",
      allowVendorFallback: false, persistSession: false, expectJson: true, timeout: timeoutMs,
    });
    if (!r || typeof r.success !== "boolean") throw new TypeError("inference returned an unexpected shape");
    if (!r.success) throw new Error(`fold inference failed: ${r.error ?? "no output"}`);
    return r.output;
  };
}

/** Stored principal facts, numbered F1.., each with the date the memory store first saw it. Reads only. */
export async function loadStoredFacts(): Promise<StoredFact[]> {
  const { read } = await import("../../TOOLS/MemoryWriter.ts");
  const { readStore, normalizeKey } = await import("../../TOOLS/MemoryEntryMeta.ts");
  const r = read(PRINCIPAL_MEMORY_PATH);
  if (!("entries" in r)) return [];
  const meta = readStore().files[relative(getClaudeDir(), PRINCIPAL_MEMORY_PATH)] ?? {};
  let fallback = "undated";
  try { fallback = statSync(PRINCIPAL_MEMORY_PATH).mtime.toISOString().slice(0, 10); } catch { /* keep undated */ }
  return r.entries.map((text, k) => ({ id: `F${k + 1}`, text, date: (meta[normalizeKey(text)]?.first_seen ?? fallback).slice(0, 10) }));
}

async function statvsWriter(): Promise<(event: FoldEvent) => void> {
  const { writeEvent } = await import("../../STATVS/lib/event.ts");
  return (event) => { writeEvent(event as never); };
}

async function main(argv: string[]): Promise<number> {
  const [command = "run", ...rest] = argv;
  const flag = (name: string) => rest.includes(name);
  const value = (name: string) => { const k = rest.indexOf(name); return k >= 0 ? rest[k + 1] : undefined; };
  const dir = value("--thread") ?? markedThreadDir();
  if (command === "status") {
    const cursor = dir ? readFoldCursor(CONTEXT_DIR, dir) : null;
    console.log(JSON.stringify({ thread: dir ? basename(dir) : null, cursor, workstreams: readWorkstreams().length }));
    return 0;
  }
  if (command !== "run") { console.error("usage: Fold.ts run [--json] [--thread <dir>] [--dry-run] | status"); return 2; }
  if (!dir) {
    const r = { ok: true, read: 0, batches: 0, proposals: 0, corrections: 0, dropped: 0, workstreams_changed: false, cursor: null, note: "no marked principal thread" };
    (await statvsWriter())(eventFor(r, new Date().toISOString()));
    console.log(JSON.stringify(r));
    return 0;
  }
  const result = await runFold({
    threadDir: dir, facts: await loadStoredFacts(), model: foldModelFromInference(),
    writeEvent: await statvsWriter(), dryRun: flag("--dry-run"),
  });
  console.log(flag("--json") ? JSON.stringify(result) : `${result.ok ? "ok" : "failed"}: read ${result.read}, proposals ${result.proposals}, corrections ${result.corrections}${result.error ? ` (${result.error})` : ""}`);
  return result.ok ? 0 : 1;
}

if (import.meta.main) process.exit(await main(process.argv.slice(2)));
