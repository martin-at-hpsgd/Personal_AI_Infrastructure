/** Read at call time, so a caller (or a test) that sets LIFEOS_DIR after import writes where it said. */
function lifeosDir(): string {
  return getLifeosDir();
}

interface FailureCaptureInput {
  transcriptPath: string;
  rating: number;
  sentimentSummary: string;
  detailedContext?: string;
  sessionId?: string;
  /**
   * 'rating'     — a real numeric rating from the principal (frontmatter keeps it).
   * 'correction' — a deterministic correction capture with NO numeric rating; the
   *   caller's `rating` is only the internal severity gate value and is NOT
   *   written as a rating (2026-08-17: every correction capture stamped a
   *   fabricated constant rating:3, poisoning downstream analysis).
   */
  captureSource?: 'rating' | 'correction';
}

interface TranscriptEntry {
  type: string;
  message?: {
    role?: string;
    content?: unknown;
  };
  timestamp?: string;
  [key: string]: unknown;
}

interface ToolCall {
  name: string;
  input: unknown;
  output?: string;
  timestamp?: string;
}

/**
 * Extract text content from Claude's content format
 */
function contentToText(content: unknown): string {
  if (typeof content === 'string') return content;
  if (Array.isArray(content)) {
    return content
      .map(c => {
        if (typeof c === 'string') return c;
        if (c?.text) return c.text;
        if (c?.content) return contentToText(c.content);
        return '';
      })
      .join('\n')
      .trim();
  }
  return '';
}

/**
 * Local secret shapes, kept as a floor under the shared redactor (`redact` from lib/Boundary).
 * Shapes mirror hooks/lib/egress-shapes.ts SECRET_VALUE_SHAPES plus common auth/env/JWT
 * forms. Added for discussion #1365. Passphrases, PINs and verification codes come from the
 * shared redactor (ISA 20261015-boundary-primitives, C6): this list never covered them.
 */
const SECRET_SHAPES: RegExp[] = [
  /\bsk-[A-Za-z0-9][A-Za-z0-9_-]{18,}/g,              // OpenAI / Anthropic / OpenRouter sk-* keys
  /\bcsk-[A-Za-z0-9]{16,}/g,                          // Cerebras
  /\bgithub_pat_[A-Za-z0-9_]{20,}/g,                  // GitHub fine-grained PAT
  /\bghp_[A-Za-z0-9]{20,}/g,                          // GitHub classic PAT
  /\bxox[baprs]-[A-Za-z0-9-]{10,}/g,                  // Slack
  /\bAKIA[0-9A-Z]{16}\b/g,                            // AWS access key id
  /-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?-----END [A-Z ]*PRIVATE KEY-----/g, // PEM block
  /\bBearer\s+[A-Za-z0-9._~+/=-]{16,}/gi,             // Authorization: Bearer <token>
  /\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g, // JWT
  // Quoted-key forms: JSON `"password":"..."` and its string-escaped twin `\"password\":\"...\"`,
  // where the closing quote of the key sits BEFORE the colon (the plain KEY=value shape below
  // needs the colon right after the name and never matched these). Any value length: a key
  // named password/token/etc. holding a short value is still a credential.
  /\b[A-Za-z0-9_-]*(?:KEY|TOKEN|SECRET|PASSWORD|PASSWD|CREDENTIAL|AUTHORIZATION)[A-Za-z0-9_-]*\\*["']\s*[=:]\s*\\*["'](?:[^"'\\\n]|\\(?!["']))+/gi,
  /\b[A-Za-z0-9_]*(?:KEY|TOKEN|SECRET|PASSWORD|PASSWD|CREDENTIAL)[A-Za-z0-9_]*\\*["']?\s*[=:]\s*\\*["']?[A-Za-z0-9._/+~-]{12,}\\*["']?/gi, // KEY=value / KEY: value (optionally quoted key and value)
  /\b(?=[A-Za-z0-9]*[A-Z])(?=[A-Za-z0-9]*[a-z])(?=[A-Za-z0-9]*\d)[A-Za-z0-9]{32,}\b/g, // bare unprefixed key (Shodan-style); mirrors egress-shapes BARE_TOKEN (ERR-20261011-081100-0c8c)
  // Unquoted NUMERIC value under a credential-named key, any length: `"password": 4821`,
  // `PIN_SECRET=90210`, `api_key: 12345`. The quoted forms above need a quote before the value and
  // the KEY=value form needs 12+ characters, so a short numeric credential passed both
  //. TOKEN(?!S) leaves plural counters such as `input_tokens: 4096`.
  /\b[A-Za-z0-9_-]*(?:KEY|TOKEN(?!S)|SECRET|PASSWORD|PASSWD|CREDENTIAL|AUTHORIZATION)[A-Za-z0-9_-]*\\*["']?\s*[=:]\s*-?\d[\d.]*(?![A-Za-z0-9._/+~-])/gi,
];

/**
 * Apply every local secret shape, then the shared redactor, replacing matches with [REDACTED].
 * A union of the two, so it only ever redacts more than either alone. Idempotent; run it on the
 * whole string before any cut.
 */
export function redactSecrets(text: string): string {
  if (!text) return text;
  let out = text;
  for (const re of SECRET_SHAPES) out = out.replace(re, '[REDACTED]');
  return redact(out);
}

const sharedKeyCache = new Map<string, boolean>();

/**
 * True when the shared redactor treats `k` as a credential key (passphrase, PIN, passcode, password,
 * api key, …), judged by the key's words. Asked through Boundary's own structured walk, so this file
 * holds no second copy of the label rules: a number under a credential key is replaced, under any
 * other key it is returned as is.
 */
function isSharedSecretKey(k: string): boolean {
  let hit = sharedKeyCache.get(k);
  if (hit === undefined) {
    hit = (boundaryRedactStructured({ [k]: 0 }) as Record<string, unknown>)[k] !== 0;
    if (sharedKeyCache.size < 4096) sharedKeyCache.set(k, hit);
  }
  return hit;
}

/** Object keys whose value is a credential no matter what it looks like. */
const SENSITIVE_KEY = /(?:key|token|secret|password|passwd|credential|authorization)/i;

/**
 * A usage counter, not a credential: the key's only credential word is the plural "tokens"
 * (input_tokens, max_tokens, tokens_used). Only a NUMBER under such a key is kept; a string
 * under it is still redacted.
 */
function isTokenCountKey(k: string): boolean {
  return /tokens/i.test(k) && !/token(?!s)/i.test(k) && !/(?:key|secret|password|passwd|credential|authorization)/i.test(k);
}

/**
 * Whether a primitive under credential-named key `k` is replaced. Strings, numbers and bigints
 * all are: a numeric password or PIN is still the credential (numbers
 * were exempt and a numeric password survived into the capture). Kept: null and '' (no
 * value to leak), booleans (one bit, e.g. has_api_key: true, holds no credential), and a number
 * under a token-count key.
 */
function redactsPrimitive(k: string, val: unknown): boolean {
  if (!SENSITIVE_KEY.test(k) && !isSharedSecretKey(k)) return false;
  if (val === null || val === '' || typeof val === 'boolean') return false;
  if (typeof val === 'number' && isTokenCountKey(k)) return false;
  return true;
}

/**
 * Redact a structured value before it is serialized: every string goes through
 * redactSecrets, and any property whose NAME says credential (password, apiKey,
 * access_token, Authorization, passphrase, PIN...) is replaced outright when its value is a
 * primitive (string, number or bigint), so neither quoting nor a numeric type
 * can hide it from the regexes. Under a key the shared redactor names a credential
 * (`credentials: {...}`, `pin: {value: ...}`), every primitive leaf below is replaced too.
 */
export function redactStructured<T>(value: T): T {
  const seen = new WeakSet<object>();
  const walk = (v: unknown, under: string | null): unknown => {
    if (under !== null && (v === null || typeof v !== 'object')) {
      return redactsPrimitive(under, v) ? '[REDACTED]' : typeof v === 'string' ? redactSecrets(v) : v;
    }
    if (typeof v === 'string') return redactSecrets(v);
    if (v === null || typeof v !== 'object') return v;
    if (seen.has(v as object)) return '[CIRCULAR]';
    seen.add(v as object);
    if (Array.isArray(v)) return v.map((x) => walk(x, under));
    const out: Record<string, unknown> = {};
    for (const [k, val] of Object.entries(v as Record<string, unknown>)) {
      const primitive = val === null || typeof val !== 'object';
      if (primitive && redactsPrimitive(k, val)) out[k] = '[REDACTED]';
      else out[k] = walk(val, under ?? (isSharedSecretKey(k) ? k : null));
    }
    return out;
  };
  return walk(value, null) as T;
}

/**
 * Redact a JSONL transcript line by line: each line that parses as JSON is
 * redacted structurally and re-serialized; a line that does not parse falls
 * back to the text shapes.
 */
export function redactJsonLines(text: string): string {
  return text
    .split('\n')
    .map((line) => {
      const t = line.trim();
      if (!t.startsWith('{') && !t.startsWith('[')) return redactSecrets(line);
      try {
        return redactSecrets(JSON.stringify(redactStructured(JSON.parse(t))));
      } catch {
        return redactSecrets(line);
      }
    })
    .join('\n');
}

/**
 * Parse transcript and extract all relevant data
 */
function parseTranscript(transcriptPath: string): {
  entries: TranscriptEntry[];
  toolCalls: ToolCall[];
  conversations: { role: string; content: string; timestamp?: string }[];
} {
  const entries: TranscriptEntry[] = [];
  const toolCalls: ToolCall[] = [];
  const conversations: { role: string; content: string; timestamp?: string }[] = [];

  try {
    const content = readFileSync(transcriptPath, 'utf-8');
    const lines = content.trim().split('\n');

    for (const line of lines) {
      if (!line.trim()) continue;
      try {
        const entry = JSON.parse(line) as TranscriptEntry;
        entries.push(entry);

        // Extract conversations
        if (entry.type === 'user' && entry.message?.content) {
          const text = contentToText(entry.message.content);
          if (text) {
            conversations.push({
              role: 'user',
              content: text,
              timestamp: entry.timestamp,
            });
          }
        }

        if (entry.type === 'assistant' && entry.message?.content) {
          const text = contentToText(entry.message.content);
          if (text) {
            conversations.push({
              role: 'assistant',
              content: text,
              timestamp: entry.timestamp,
            });
          }

          // Extract tool calls
          if (Array.isArray(entry.message.content)) {
            for (const block of entry.message.content as any[]) {
              if (block.type === 'tool_use') {
                toolCalls.push({
                  name: block.name,
                  input: block.input,
                  timestamp: entry.timestamp,
                });
              }
            }
          }
        }

        // Capture tool results
        if (entry.type === 'tool_result' || entry.type === 'tool_output') {
          const lastToolCall = toolCalls[toolCalls.length - 1];
          if (lastToolCall && !lastToolCall.output) {
            lastToolCall.output = contentToText((entry as any).content || (entry as any).output);
          }
        }
      } catch {
        // Skip malformed lines
      }
    }
  } catch (err) {
    console.error(`[FailureCapture] Error parsing transcript: ${err}`);
  }

  return { entries, toolCalls, conversations };
}

const DESCRIPTION_FALLBACK = 'unspecified-failure-needs-manual-review';
const DESCRIPTION_SHAPE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function wordsOf(text: string): string[] {
  return text.toLowerCase().match(/[a-z0-9]+/g) ?? [];
}

/**
 * Lower-case words the shared redactor removes from `raw`: present in the raw text and absent
 * from its redacted form. These are credential words (a passphrase's words, a PIN), and none of
 * them may appear in a directory name, even when a model echoes them back in kebab case.
 */
export function redactedAwayWords(raw: string): Set<string> {
  const kept = new Set(wordsOf(redactSecrets(raw)));
  return new Set(wordsOf(raw).filter((w) => !kept.has(w)));
}

/**
 * Turn any candidate text (a model reply, or the summary) into description words built only
 * from redacted text: redact it whole, drop the [REDACTED] marks and every word in `removed`, and
 * repeat until redaction leaves it unchanged. Empty when nothing safe is left.
 */
export function safeDescriptionWords(candidate: string, removed: Set<string>): string[] {
  let words = wordsOf(candidate);
  for (let pass = 0; pass < 4; pass++) {
    const spaced = words.join(' ');
    const clean = redactSecrets(spaced);
    words = wordsOf(clean.replace(/\[REDACTED\]/g, ' ')).filter((w) => !removed.has(w));
    if (clean === spaced && words.join(' ') === spaced) return words;
  }
  return [];
}

/** The fallback description: the first eight safe words of the summary. */
export function fallbackDescription(sentimentSummary: string, removed: Set<string> = redactedAwayWords(sentimentSummary)): string {
  const words = safeDescriptionWords(sentimentSummary.replace(/[^A-Za-z0-9\s]/g, ''), removed).slice(0, 8);
  return words.length > 0 ? words.join('-') : DESCRIPTION_FALLBACK;
}

/** A model's reply cleaned into a description: safe words only, about eight of them. */
export function cleanDescription(reply: string, sentimentSummary: string, removed: Set<string>): string {
  const words = safeDescriptionWords(reply.replace(/[^A-Za-z0-9\s-]/g, ''), removed);
  if (words.length === 0) return fallbackDescription(sentimentSummary, removed);
  if (words.length > 10) return words.slice(0, 8).join('-');
  if (words.length < 5) return ['low', 'rating', 'failure', ...words].join('-');
  return words.join('-');
}

/**
 * Generate 8-word description using fast inference. Everything sent to the model is redacted
 * whole before any cut, and the reply is cleaned against the words redaction removed.
 */
async function generateDescription(
  sentimentSummary: string,
  conversations: { role: string; content: string }[],
  toolCalls: ToolCall[]
): Promise<string> {
  const recent = conversations.slice(-6);
  const removed = redactedAwayWords([sentimentSummary, ...recent.map((c) => c.content)].join('\n'));

  // Get last few exchanges for context
  const recentConvos = recent.map(c =>
    `${c.role.toUpperCase()}: ${redactSecrets(c.content).slice(0, 200)}`
  ).join('\n');

  const recentTools = toolCalls.slice(-5).map(t => t.name).join(', ');

  const systemPrompt = `Generate a SHORT, SPECIFIC description of what went wrong in this AI assistant interaction.

REQUIREMENTS:
- EXACTLY 8 words (count them!)
- Use lowercase with hyphens between words (kebab-case)
- Be specific about the actual failure, not generic
- Focus on what the assistant did wrong or what frustrated the user

EXAMPLES OF GOOD DESCRIPTIONS:
- "assistant-deleted-users-file-without-asking-permission-first"
- "ignored-explicit-python-prohibition-and-used-it-anyway"
- "claimed-task-complete-when-build-was-still-failing"
- "overwrote-working-code-with-broken-implementation-silently"
- "asked-clarifying-question-instead-of-just-doing-task"

EXAMPLES OF BAD DESCRIPTIONS:
- "user-was-frustrated-with-assistant-response-quality" (too generic)
- "error" (too short, not descriptive)
- "the-assistant-made-a-mistake-on-this-task" (still too generic)

OUTPUT: Return ONLY the 8-word description, nothing else.`;

  const userPrompt = `SENTIMENT: ${redactSecrets(sentimentSummary)}

RECENT CONVERSATION:
${recentConvos}

TOOLS USED: ${recentTools || 'none'}

Generate the 8-word description:`;

  try {
    const result = await inference({
      systemPrompt,
      userPrompt,
      // v6.9.0: medium not low — subprocess cold-start dominates total
      // latency, so Sonnet adds ~1-2s vs Haiku, and the default 30s timeout
      // gives ~3x the headroom of the prior 10s window. Subscription billing
      // makes per-call cost irrelevant.
      level: 'medium',
    });

    if (result.success && result.output) {
      return cleanDescription(result.output.trim(), sentimentSummary, removed);
    }
  } catch (err) {
    console.error(`[FailureCapture] Inference error: ${err}`);
  }

  // Fallback: derive from the redacted sentiment summary
  return fallbackDescription(sentimentSummary, removed);
}

/**
 * Get PST timestamp components
 */
function getPSTComponents(): {
  year: string;
  month: string;
  day: string;
  hours: string;
  minutes: string;
  seconds: string;
} {
  const now = new Date();
  const pst = new Date(now.toLocaleString('en-US', { timeZone: principalTimezone() }));

  return {
    year: pst.getFullYear().toString(),
    month: String(pst.getMonth() + 1).padStart(2, '0'),
    day: String(pst.getDate()).padStart(2, '0'),
    hours: String(pst.getHours()).padStart(2, '0'),
    minutes: String(pst.getMinutes()).padStart(2, '0'),
    seconds: String(pst.getSeconds()).padStart(2, '0'),
  };
}

