#!/usr/bin/env bun
/**
 * EvalState — self-contained, publish-clean eval state inside each skill.
 *
 * Writes `skills/<X>/EvalState.md` for every skill whose SKILL.md frontmatter
 * `evals:` names a suite that just ran: current grade (pass^k, mean±SEM, judge,
 * ts), trend derived from the last two persisted runs (no duplicate state), and
 * an append-only iteration log (`date | change | suite | before → after`) so a
 * skill carries its own upgrade history the way auto-research needs.
 *
 * SECURITY CONTRACT (the install's skill eval-state rules): emits scores,
 * dates, suite names, and caller-supplied one-line notes ONLY — never case
 * prompts, outputs, or transcripts (those stay in MEMORY/STATE/Evals-Results).
 * Iteration notes are deny-scanned at WRITE TIME against the canonical
 * deny-list + scrub patterns; a matching note is refused, not laundered.
 * EvalState.md is release-excluded (ShadowRelease) and version-exempt
 * (BumpSkillVersions) — machine telemetry, not skill content.
 *
 *   (library)  updateSkillStates(suite, result)     — called by EvalRunner post-run
 *   (cli)      bun EvalState.ts log-iteration --skill <X> --suite <s> --note "..."
 */

import { existsSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { homedir } from 'node:os';
import { parseArgs } from 'node:util';
import { invariant } from '../../../LIFEOS/TOOLS/Invariant';
import { skillSuiteNames } from '../../../LIFEOS/TOOLS/lib/SkillVerificationCoverage.ts';
import { createHash } from 'node:crypto';
import { resolveSuiteDefinition, resolveVendors } from '../../../LIFEOS/TOOLS/lib/Calibration.ts';
import { assayUserDir, getClaudeDir } from '../../../LIFEOS/TOOLS/Paths.ts';
import { parse as parseYaml } from 'yaml';

const CLAUDE_ROOT = getClaudeDir();
const SKILLS_DIR = join(CLAUDE_ROOT, 'skills');
const RESULTS_DIR = join(CLAUDE_ROOT, 'LIFEOS', 'MEMORY', 'STATE', 'Evals-Results');
const DENY_PATHS = [
  join(CLAUDE_ROOT, 'LIFEOS', 'USER', 'SECURITY', 'DENY_LIST.txt'),
  join(CLAUDE_ROOT, 'LIFEOS', 'USER', 'SECURITY', 'PublicScrubPatterns.txt'),
];

const HEADER = `<!-- AUTO-GENERATED by skills/Assay/Tools/EvalState.ts — machine-owned; hand edits are overwritten.
     Contract: scores, dates, suite names, and neutral one-line notes ONLY. Outputs, prompts, and
     transcripts live in MEMORY/STATE/Evals-Results/, never here. Release-excluded; version-exempt. -->`;

interface RunSummary {
  ts?: string;
  score: number;
  pass_to_k: number;
  stats?: { sem: number };
  judge_level?: string;
  type?: string;
  verifier_unavailable?: boolean;
  evidence?: EvidenceBinding;
}

export interface EvidenceBinding { suite: string; skills: Record<string, string> }

/** Only explicit eval runs/status refreshes hash content; monitor ticks never do. */
export function skillContentHash(dir: string): string {
  const hash = createHash('sha256');
  const ignored = new Set(['node_modules', '.git', 'EvalState.md', 'bun.lock', 'bun.lockb']);
  function walk(path: string, prefix = ''): void {
    for (const e of readdirSync(path, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (ignored.has(e.name) || e.name.startsWith('.')) continue;
      const rel = prefix + e.name;
      if (e.isDirectory()) walk(join(path, e.name), rel + '/');
      else if (e.isFile() && /\.(md|ts|js|json|yaml|yml)$/.test(e.name)) hash.update(rel).update(readFileSync(join(path, e.name)));
    }
  }
  walk(dir);
  return hash.digest('hex');
}

export function captureEvidence(suite: string, root = CLAUDE_ROOT): EvidenceBinding | undefined {
  const definition = resolveSuiteDefinition(suite, [join(assayUserDir(join(root, 'LIFEOS')), 'Suites'), join(root, 'skills/Assay/Suites')]);
  if (!definition) return undefined;
  const hash = createHash('sha256').update(readFileSync(definition.path));
  const config = parseYaml(readFileSync(definition.path, 'utf8')) as { system_prompt_file?: string; system_prompt?: string; append_to_base?: boolean; cases?: { image?: string }[] };
  const artifactPath = (p: string) => p.startsWith('~/') ? join(homedir(), p.slice(2)) : resolve(dirname(definition.path), p);
  const inputs = [...(config.system_prompt_file ? [artifactPath(config.system_prompt_file)] : []),
    ...(config.cases ?? []).flatMap(c => c.image ? [artifactPath(c.image)] : [])];
  if ((!config.system_prompt && !config.system_prompt_file) || config.append_to_base) inputs.push(
    join(root, 'LIFEOS/LIFEOS_SYSTEM_PROMPT.md'), join(root, 'LIFEOS/USER/DIGITAL_ASSISTANT/DA_IDENTITY.md'));
  for (const path of inputs) hash.update(existsSync(path) ? readFileSync(path) : `missing:${path}`);
  // Bind shared execution and grading dependencies, not just the rubric text.
  for (const p of ['LIFEOS/TOOLS/models.ts', 'LIFEOS/TOOLS/Inference.ts', 'LIFEOS/TOOLS/lib/JudgePrompts.ts', 'LIFEOS/TOOLS/lib/Calibration.ts']) {
    const f = join(root, p); if (existsSync(f)) hash.update(p).update(readFileSync(f));
  }
  const evalDir = join(root, 'skills/Assay');
  if (existsSync(evalDir)) hash.update(skillContentHash(evalDir));
  hash.update(JSON.stringify(resolveVendors()));
  const skills: Record<string, string> = {};
  for (const skill of skillsForSuite(suite, join(root, 'skills'))) skills[skill] = skillContentHash(join(root, 'skills', skill));
  return { suite: hash.digest('hex'), skills };
}

export function evidenceStatus(run: RunSummary, current: EvidenceBinding | undefined, skill: string): string {
  if (run.verifier_unavailable) return 'unavailable';
  if (!run.evidence || !current) return 'unbound historical result';
  if (run.evidence.suite !== current.suite || !run.evidence.skills[skill] || run.evidence.skills[skill] !== current.skills[skill]) return 'stale: content or execution changed';
  return 'current';
}

/** Last N persisted runs for a suite, newest first (run ids sort by timestamp prefix). */
function recentRuns(suite: string, n: number, includeUnavailable = false): RunSummary[] {
  const dir = join(RESULTS_DIR, suite);
  if (!existsSync(dir)) return [];
  const out: RunSummary[] = [];
  for (const r of readdirSync(dir).filter((d) => d.startsWith('run_')).sort().reverse()) {
    if (out.length >= n) break;
    try {
      const run = JSON.parse(readFileSync(join(dir, r, 'run.json'), 'utf-8')) as RunSummary;
      // A no-verdict run (every inference call failed) is history, not a grade.
      if (includeUnavailable || !run.verifier_unavailable) out.push(run);
    } catch { /* skip corrupt */ }
  }
  return out;
}

function pct(x: number): string { return `${(x * 100).toFixed(0)}%`; }

function gradeLine(suite: string, skill: string): { current: string; before?: string } {
  const runs = recentRuns(suite, 2);
  const latestAttempt = recentRuns(suite, 1, true)[0];
  if (runs.length === 0) return { current: `| ${suite} | — | — | — | — | ${latestAttempt?.verifier_unavailable ? 'latest attempt unavailable; no valid verdict' : 'never run'} |` };
  const [cur, prev] = runs;
  const status = evidenceStatus(cur, captureEvidence(suite), skill);
  const trend = prev === undefined ? 'first run'
    : cur.pass_to_k > prev.pass_to_k ? `↑ from ${pct(prev.pass_to_k)}`
    : cur.pass_to_k < prev.pass_to_k ? `↓ from ${pct(prev.pass_to_k)}`
    : '→ flat';
  const sem = cur.stats ? ` ±${(cur.stats.sem * 100).toFixed(1)}` : '';
  return {
    current: `| ${suite} | ${pct(cur.pass_to_k)} | ${(cur.score * 100).toFixed(1)}%${sem} | ${status === 'current' && prev?.evidence?.suite === cur.evidence?.suite && prev?.evidence?.skills[skill] === cur.evidence?.skills[skill] ? trend : 'not comparable'} | ${cur.judge_level ?? '?'} | ${(cur.ts ?? '').slice(0, 16)}; ${status}${latestAttempt?.verifier_unavailable ? '; latest attempt unavailable' : ''} |`,
    before: prev ? `${pct(prev.pass_to_k)}` : undefined,
  };
}

/** Skills whose frontmatter `evals:` names this suite. */
export function skillsForSuite(suite: string, skillsDir = SKILLS_DIR): string[] {
  const hits: string[] = [];
  for (const d of readdirSync(skillsDir, { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const md = join(skillsDir, d.name, 'SKILL.md');
    if (!existsSync(md)) continue;
    try {
      const names = skillSuiteNames(readFileSync(md, 'utf-8'));
      if (names.includes(suite)) hits.push(d.name);
    } catch { /* unreadable skill — skip */ }
  }
  return hits;
}

function readSections(path: string): { iterations: string[] } {
  if (!existsSync(path)) return { iterations: [] };
  const body = readFileSync(path, 'utf-8');
  const iter = body.split('## Iterations')[1] ?? '';
  return { iterations: iter.split('\n').filter((l) => l.startsWith('| 20')) };
}

function writeState(skill: string, iterationRows: string[]): void {
  const md = join(SKILLS_DIR, skill, 'SKILL.md');
  const suites = skillSuiteNames(readFileSync(md, 'utf-8'));
  if (suites.length === 0) return; // declined or empty — no state file
  const rows = suites.map((s) => gradeLine(s, skill).current).join('\n');
  const iterBlock = iterationRows.length
    ? iterationRows.join('\n')
    : '_none yet — append via `bun skills/Assay/Tools/EvalState.ts log-iteration`_';
  const out = `${HEADER}

# Eval State — ${skill}

## Current

| suite | pass^k | mean | trend | judge | last run |
|---|---|---|---|---|---|
${rows}

## Iterations

| date | change | suite | before → after |
|---|---|---|---|
${iterBlock}
`;
  const outPath = join(SKILLS_DIR, skill, 'EvalState.md');
  invariant(!/## OUTPUT|```|dataUrl/.test(out), 'EvalState carries no output/transcript content');
  writeFileSync(outPath, out);
}

/** Post-run entry point for EvalRunner: refresh state for every skill bound to this suite. */
export function updateSkillStates(suite: string): string[] {
  const updated: string[] = [];
  for (const skill of skillsForSuite(suite)) {
    const prior = readSections(join(SKILLS_DIR, skill, 'EvalState.md'));
    writeState(skill, prior.iterations);
    updated.push(skill);
  }
  return updated;
}

function denyScan(note: string): string | null {
  for (const p of DENY_PATHS) {
    if (!existsSync(p)) continue;
    for (const raw of readFileSync(p, 'utf-8').split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))) {
      try { if (new RegExp(raw, 'i').test(note)) return raw.slice(0, 24); } catch { /* non-JS regex line — skip */ }
    }
  }
  if (/\/Users\/[a-z][a-z0-9_-]+\/|\/home\/[a-z][a-z0-9_-]+\//.test(note)) return 'home-path';
  return null;
}

if (import.meta.main) {
  const [cmd] = Bun.argv.slice(2);
  const { values } = parseArgs({
    args: Bun.argv.slice(3),
    options: { skill: { type: 'string' }, suite: { type: 'string' }, note: { type: 'string' } },
  });
  if (cmd === 'update' && values.suite) {
    const updated = updateSkillStates(values.suite);
    console.log(updated.length ? `updated: ${updated.join(', ')}` : `no skill binds suite '${values.suite}'`);
    process.exit(0);
  }
  if (cmd === 'log-iteration' && values.skill && values.suite && values.note) {
    invariant(values.note.length <= 200, 'iteration note is one line (≤200 chars)');
    const hit = denyScan(values.note);
    if (hit) { console.error(`REFUSED: note matches deny pattern (${hit}…) — iteration notes must be publish-clean.`); process.exit(1); }
    const runs = recentRuns(values.suite, 2);
    const after = runs[0] ? `${(runs[0].pass_to_k * 100).toFixed(0)}%` : '—';
    const before = runs[1] ? `${(runs[1].pass_to_k * 100).toFixed(0)}%` : '—';
    const path = join(SKILLS_DIR, values.skill, 'EvalState.md');
    const prior = readSections(path);
    prior.iterations.push(`| ${new Date().toISOString().slice(0, 10)} | ${values.note.replace(/\|/g, '/')} | ${values.suite} | ${before} → ${after} |`);
    writeState(values.skill, prior.iterations);
    console.log(`logged: ${values.skill} · ${values.suite} · ${before} → ${after}`);
    process.exit(0);
  }
  console.log(`EvalState — in-skill eval state\n\n  bun EvalState.ts update --suite <s>\n  bun EvalState.ts log-iteration --skill <X> --suite <s> --note "one line"`);
  process.exit(1);
}
